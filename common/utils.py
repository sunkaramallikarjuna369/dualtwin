def create_twin_comparison_data(
    physical_values: List[float],
    twin_values: List[float],
    timestamps: Optional[List[datetime]] = None
) -> pd.DataFrame:
    """Create a DataFrame for comparing physical and twin values."""
    if timestamps is None:
        timestamps = [datetime.now() + timedelta(seconds=i) for i in range(len(physical_values))]
    
    return pd.DataFrame({
        'timestamp': timestamps,
        'physical': physical_values,
        'twin': twin_values,
        'difference': [p - t for p, t in zip(physical_values, twin_values)]
    })


def format_value(value: float, unit: str, precision: int = 2) -> str:
    """Format a value with its unit for display."""
    return f"{value:.{precision}f} {unit}"


