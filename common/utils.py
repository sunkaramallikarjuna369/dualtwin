def generate_id(prefix: str = "DT") -> str:
    """Generate a unique ID for twins, sensors, or alerts."""
    timestamp = int(time.time() * 1000)
    random_part = random.randint(1000, 9999)
    return f"{prefix}-{timestamp}-{random_part}"


