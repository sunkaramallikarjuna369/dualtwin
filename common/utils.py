@dataclass
class SensorReading:
    """Represents a single sensor reading from a physical asset."""
    sensor_id: str
    timestamp: datetime
    value: float
    unit: str
    quality: float = 1.0  # Data quality score 0-1
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            'sensor_id': self.sensor_id,
            'timestamp': self.timestamp.isoformat(),
            'value': self.value,
            'unit': self.unit,
            'quality': self.quality
        }


@dataclass
class TwinState:
    """Represents the current state of a digital twin."""
    twin_id: str
    timestamp: datetime
    properties: Dict[str, Any] = field(default_factory=dict)
    status: str = "active"
    health_score: float = 1.0
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            'twin_id': self.twin_id,
            'timestamp': self.timestamp.isoformat(),
            'properties': self.properties,
            'status': self.status,
            'health_score': self.health_score
        }
    
    def update_property(self, key: str, value: Any) -> None:
        """Update a single property of the twin."""
        self.properties[key] = value
        self.timestamp = datetime.now()


@dataclass
class Alert:
    """Represents an alert generated by the digital twin system."""
    alert_id: str
    twin_id: str
    timestamp: datetime
    severity: str  # 'info', 'warning', 'critical'
    message: str
    source: str
    acknowledged: bool = False
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            'alert_id': self.alert_id,
            'twin_id': self.twin_id,
            'timestamp': self.timestamp.isoformat(),
            'severity': self.severity,
            'message': self.message,
            'source': self.source,
            'acknowledged': self.acknowledged
        }


