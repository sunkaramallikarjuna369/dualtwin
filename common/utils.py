class TwinLogger:
    """Logger specifically for digital twin operations."""
    
    def __init__(self, twin_id: str, log_file: Optional[str] = None):
        self.twin_id = twin_id
        self.logger = logging.getLogger(f'dualtwin.{twin_id}')
        self.events: List[Dict[str, Any]] = []
        
        if log_file:
            handler = logging.FileHandler(log_file)
            handler.setFormatter(logging.Formatter(
                '%(asctime)s - %(name)s - %(levelname)s - %(message)s'
            ))
            self.logger.addHandler(handler)
    
    def log_state_update(self, old_state: Dict, new_state: Dict) -> None:
        """Log a state update event."""
        event = {
            'type': 'state_update',
            'timestamp': datetime.now().isoformat(),
            'twin_id': self.twin_id,
            'old_state': old_state,
            'new_state': new_state
        }
        self.events.append(event)
        self.logger.info(f"State updated: {old_state} -> {new_state}")
    
    def log_alert(self, alert: Alert) -> None:
        """Log an alert event."""
        event = {
            'type': 'alert',
            'timestamp': datetime.now().isoformat(),
            'twin_id': self.twin_id,
            'alert': alert.to_dict()
        }
        self.events.append(event)
        log_method = getattr(self.logger, alert.severity, self.logger.info)
        log_method(f"Alert: {alert.message}")
    
    def log_sync(self, source: str, data_points: int) -> None:
        """Log a synchronization event."""
        event = {
            'type': 'sync',
            'timestamp': datetime.now().isoformat(),
            'twin_id': self.twin_id,
            'source': source,
            'data_points': data_points
        }
        self.events.append(event)
        self.logger.info(f"Synced {data_points} data points from {source}")
    
    def get_events(self, event_type: Optional[str] = None) -> List[Dict[str, Any]]:
        """Get logged events, optionally filtered by type."""
        if event_type:
            return [e for e in self.events if e['type'] == event_type]
        return self.events


