class SensorSimulator:
    """Simulates sensor data streams for digital twin demonstrations."""
    
    def __init__(
        self,
        sensor_id: str,
        base_value: float,
        noise_level: float = 0.1,
        drift_rate: float = 0.001,
        unit: str = "units"
    ):
        self.sensor_id = sensor_id
        self.base_value = base_value
        self.noise_level = noise_level
        self.drift_rate = drift_rate
        self.unit = unit
        self.current_drift = 0.0
        self.reading_count = 0
    
    def generate_reading(self) -> SensorReading:
        """Generate a single sensor reading with noise and drift."""
        self.reading_count += 1
        self.current_drift += random.gauss(0, self.drift_rate)
        
        noise = random.gauss(0, self.noise_level * self.base_value)
        value = self.base_value + self.current_drift + noise
        
        quality = max(0.0, min(1.0, 1.0 - abs(noise) / (self.base_value * 0.5)))
        
        return SensorReading(
            sensor_id=self.sensor_id,
            timestamp=datetime.now(),
            value=value,
            unit=self.unit,
            quality=quality
        )
    
    def generate_stream(self, count: int, interval_seconds: float = 1.0) -> List[SensorReading]:
        """Generate a stream of sensor readings."""
        readings = []
        base_time = datetime.now()
        
        for i in range(count):
            reading = self.generate_reading()
            reading.timestamp = base_time + timedelta(seconds=i * interval_seconds)
            readings.append(reading)
        
        return readings
    
    def reset(self) -> None:
        """Reset the simulator state."""
        self.current_drift = 0.0
        self.reading_count = 0


class PhysicsModel:
    """Simple physics model for simulating physical system behavior."""
    
    def __init__(self, model_type: str = "thermal"):
        self.model_type = model_type
        self.state = {}
    
    def thermal_model(
        self,
        current_temp: float,
        ambient_temp: float,
        heat_input: float,
        thermal_mass: float = 100.0,
        heat_transfer_coeff: float = 0.1,
        dt: float = 1.0
    ) -> float:
        """
        Simple thermal model: dT/dt = (Q_in - h*(T - T_ambient)) / C
        
        Args:
            current_temp: Current temperature
            ambient_temp: Ambient temperature
            heat_input: Heat input (W)
            thermal_mass: Thermal mass/capacity (J/K)
            heat_transfer_coeff: Heat transfer coefficient (W/K)
            dt: Time step (s)
        
        Returns:
            New temperature after time step
        """
        heat_loss = heat_transfer_coeff * (current_temp - ambient_temp)
        temp_change = (heat_input - heat_loss) / thermal_mass * dt
        return current_temp + temp_change
    
    def mechanical_model(
        self,
        position: float,
        velocity: float,
        force: float,
        mass: float = 1.0,
        friction: float = 0.1,
        dt: float = 0.01
    ) -> Tuple[float, float]:
        """
        Simple mechanical model: F = ma with friction
        
        Args:
            position: Current position
            velocity: Current velocity
            force: Applied force
            mass: Object mass
            friction: Friction coefficient
            dt: Time step
        
        Returns:
            Tuple of (new_position, new_velocity)
        """
        friction_force = -friction * velocity
        acceleration = (force + friction_force) / mass
        new_velocity = velocity + acceleration * dt
        new_position = position + new_velocity * dt
        return new_position, new_velocity
    
    def fluid_flow_model(
        self,
        inlet_pressure: float,
        outlet_pressure: float,
        pipe_resistance: float = 1.0
    ) -> float:
        """
        Simple fluid flow model: Q = (P_in - P_out) / R
        
        Args:
            inlet_pressure: Inlet pressure
            outlet_pressure: Outlet pressure
            pipe_resistance: Flow resistance
        
        Returns:
            Flow rate
        """
        return (inlet_pressure - outlet_pressure) / pipe_resistance


